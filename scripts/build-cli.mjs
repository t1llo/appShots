#!/usr/bin/env node
// Writes cli/appshots.mjs: the CLI as one file, bundled from the modules in cli/src. One file is what the server
// hands out at /cli/appshots.mjs, what `appshots update` replaces and what the skill finds next to itself, and it
// runs on Node 18 with nothing installed. Run `npm run build:cli` after changing cli/src; `npm run check:cli`
// fails when the file in the repository is not what the sources make.

import { chmodSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { rolldown } from "rolldown";

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "cli", "appshots.mjs");

// The shebang comes from cli/src/main.mjs; this goes right under it.
const BANNER = `// Generated from cli/src by \`npm run build:cli\`. Do not edit this file: change the modules in cli/src and
// build it again.
//
// Mac-side companion to an appShots server: builds the app in the current folder and runs it in a
// simulator, captures screenshots from a simulator or a connected iPhone/iPad, uploads them, and pulls the
// rendered store screenshots back down, or puts them into App Store Connect. There are three ways to the
// screenshots: \`appshots upload\` takes the ones that exist already, \`appshots shoot\` captures while a person
// opens each screen, and \`appshots run\` and \`appshots launch\` start the app on a given screen and capture it
// in one go. An app that is not built with Xcode alone is started by its own toolkit and captured where it
// runs: in the simulator, in a window on this Mac (\`capture --mac\`), or as a page in a browser
// (\`capture --web\`). \`appshots check\` reports what is there to work with, \`appshots setup\` installs the
// appshots skill for a coding agent and connects that agent to the server, \`appshots update\` brings that
// skill up to date, and \`appshots call\` reaches the server's tools for agents that have no MCP.
// No dependencies, so it runs straight from a checkout: \`node cli/appshots.mjs\` or \`npm link\`.
`;

const bundle = await rolldown({
  input: path.join(root, "cli", "src", "main.mjs"),
  platform: "node",
  cwd: root,
  // Node's own modules stay imports; nothing else may, as the file has to stand alone.
  external: [/^node:/],
});
const { output } = await bundle.generate({
  format: "esm",
  banner: BANNER,
  comments: { jsdoc: true, legal: true, annotation: false },
});
await bundle.close();

const [chunk, ...more] = output;
if (more.length > 0 || chunk.type !== "chunk") throw new Error(`The CLI came out as ${output.length} files; it has to be one.`);
const imports = [...chunk.code.matchAll(/^import .* from "([^"]+)";$/gm)].map((match) => match[1]).filter((name) => !name.startsWith("node:"));
if (imports.length > 0) throw new Error(`The CLI imports ${imports.join(", ")}, and it has to stand alone.`);
if (!chunk.code.startsWith("#!/usr/bin/env node\n")) throw new Error("The CLI has to start with #!/usr/bin/env node: older copies check for it before they replace themselves.");

let before = "";
try {
  before = readFileSync(out, "utf8");
} catch {}
if (before !== chunk.code) writeFileSync(out, chunk.code);
chmodSync(out, 0o755);
console.log(`${before === chunk.code ? "Unchanged" : "Wrote"} ${path.relative(root, out)} (${Math.round(chunk.code.length / 1024)} KB)`);
